const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../public/assets/visit-schedule.js'), 'utf8');
const fields = Object.fromEntries(['visitSchedule', 'visitScheduleMode', 'visitScheduleDates', 'visitScheduleStart', 'visitScheduleEnd', 'visitStartHour', 'visitEndHour', 'visitSchedulePreview'].map(id => [id, { value: '', parentElement: {}, setCustomValidity(message) { this.error = message; } }]));
fields.visitSchedule.querySelectorAll = () => ['visitScheduleMode', 'visitScheduleStart', 'visitScheduleEnd', 'visitStartHour', 'visitEndHour'].map(id => fields[id]);
const context = vm.createContext({ document: { querySelector: selector => fields[selector.slice(1)], getElementById: id => fields[id] }, workStatusInput: { value: '방문예정' } });
vm.runInContext(source, context);
const record = { work_status: '방문예정' };
assert.equal(context.visitScheduleDisplay(record), '일정 미정');
record.visit_schedule = { mode: 'range', start_date: '2026-11-03', end_date: '2026-11-05', start_hour: 9, end_hour: 15 };
assert.equal(context.visitScheduleDisplay(record), '2026-11-03 ~ 2026-11-05 방문예정 · 오전 9시 ~ 오후 3시');
context.fillVisitSchedule(record);
context.updateVisitSchedule();
assert.equal(fields.visitSchedule.hidden, false);
assert.equal(fields.visitEndHour.error, '');
fields.visitEndHour.value = '8';
context.updateVisitSchedule();
assert.ok(fields.visitEndHour.error);
fields.visitScheduleEnd.value = '2026-11-02';
context.updateVisitSchedule();
assert.ok(fields.visitScheduleEnd.error);
fields.visitScheduleMode.value = 'undecided';
context.updateVisitSchedule();
assert.equal(fields.visitEndHour.disabled, true);
assert.equal(fields.visitEndHour.error, '');
assert.equal(fields.visitSchedulePreview.textContent, '일정 미정');
record.visit_schedule = { mode: 'single', start_date: '2026-11-03', end_date: '2026-11-03', start_hour: 0, end_hour: 12 };
assert.equal(context.visitScheduleDisplay(record), '2026-11-03 방문예정 · 오전 12시 ~ 오후 12시');
record.visit_schedule = JSON.stringify(record.visit_schedule);
context.fillVisitSchedule(record);
context.updateVisitSchedule();
assert.equal(fields.visitScheduleEnd.disabled, true);
assert.equal(context.visitScheduleValue().end_date, '2026-11-03');
context.workStatusInput.value = '작업완료';
context.updateVisitSchedule();
assert.equal(fields.visitSchedule.hidden, true);
assert.equal(context.visitScheduleDisplay({ ...record, work_status: '작업완료' }), '');
console.log('PASS: schedule display, reload, date order, hourly validation and hidden fields');
